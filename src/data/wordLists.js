/**
 * 从词库中随机选取 count 个单词
 */
export function getDailyWords(vocab, count) {
  if (!Array.isArray(vocab) || vocab.length === 0) return [];
  const shuffled = [...vocab].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, vocab.length));
}
